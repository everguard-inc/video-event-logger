from PySide6.QtWidgets import QDialog, QDialogButtonBox, QTextBrowser, QVBoxLayout, QWidget


HELP_TEXT = """Video Event Logger: інструкція для анотаторів

Призначення

Додаток потрібен для перегляду відео та розмітки інтервалів, у яких відбувається подія. Кожен інтервал зберігається як:

start time + end time + event_type + comment

Основний сценарій

1. Виберіть File → Open Video… або натисніть Ctrl/Cmd+O та відкрийте .mp4 чи .mkv файл.
2. Запустіть відтворення.
3. Коли подія починається, натисніть A або кнопку Start. З'явиться жовтий індикатор INTERVAL ACTIVE з точним часом початку.
4. Продовжуйте дивитися відео.
5. Коли подія завершується, натисніть D або кнопку End.
6. Якщо увімкнений popup, підтвердіть або змініть event_type і comment.
7. Продовжуйте розмічати наступні інтервали.
8. Єдиний annotation JSON створюється одразу після відкриття відео, навіть без інтервалів, і автоматично оновлюється після кожної зміни. File → Validate & Save Annotations виконує явну перевірку та повторний запис.
9. Для надсилання на сервер один раз заповніть Connection → Settings…, а потім використовуйте File → Upload Annotations… для поточного відео.

Перегляд і редагування інтервалів

- Play у рядку інтервалу відтворює відео від Start до End і автоматично ставить паузу.
- Edit у рядку інтервалу дозволяє змінити event_type і comment. Timestamp-и не редагуються.
- Delete видаляє вибраний інтервал.
- Double click по рядку переходить на Start цього інтервалу.

Клавіші

Space          Play / pause
F11            Увімкнути або вимкнути повноекранний режим
A              Початок інтервалу
D              Кінець інтервалу
Q              Скасувати незавершений інтервал
Escape         Вийти з fullscreen
Delete         Видалити вибраний інтервал
Left           Назад на 1 секунду
Right          Вперед на 1 секунду
Shift + Left   Назад на 10 секунд
Shift + Right  Вперед на 10 секунд
,              Назад на 1 кадр
.              Вперед на 1 кадр
1              Швидкість відтворення x1
2              Швидкість відтворення x2
4              Швидкість відтворення x4
8              Швидкість відтворення x8

Активні стани керування

Підсвічена кнопка Play/Pause означає, що відео зараз відтворюється. Серед кнопок x1, x2, x4 і x8 підсвічується поточна швидкість. Кнопки Start і End окремо показують активний незавершений інтервал.

Поки інтервал активний, повторне натискання Start або A не змінює його початковий timestamp. Завершіть інтервал через End/D або скасуйте через Q.

Fullscreen і тема

Пункт View → Video Full Screen, клавіша F11 або подвійний клік по відео розгортає саме відео на весь екран. Меню, основний timeline, таблиця та панелі тимчасово ховаються, але гарячі клавіші анотації продовжують працювати. Унизу з'являється компактний HUD: робочий seek-повзунок, current/duration, PLAYING/PAUSED і поточна швидкість. Він ховається через 3 секунди бездіяльності та повертається після руху миші, Play/Pause, зміни швидкості, seek або frame step; hover і drag не дозволяють йому сховатися. Єдина верхня зона статусу постійно показує активний Start незалежно від налаштування popup, а після завершення або скасування коротко показує Interval added або Interval canceled. Окремих повідомлень по центру немає; помилки збереження також з'являються у верхній зоні та залишаються на екрані. Натисніть Escape, F11 або двічі клацніть відео поза HUD, щоб повернути звичайний інтерфейс. Тема знаходиться у View → View mode → Bright/Dark, а popup — у View → Show Interval Details Popup; обидва вибори зберігаються.

event_type

Поле event_type задає тип або категорію для нових інтервалів. Після редагування натисніть Enter або зачекайте кілька секунд, поки додаток застосує значення. Якщо поле порожнє, буде використано "undefined".

Popup після інтервалу

Якщо увімкнено View → Show Interval Details Popup, після End додаток поставить відео на паузу і попросить підтвердити event_type та додати comment. Якщо натиснути Cancel у popup, поточний інтервал не буде збережено. Стан пункту меню зберігається для наступного запуску застосунку.

Якщо активний інтервал доходить до кінця відео, додаток автоматично використовує точну тривалість відео як End. Якщо popup увімкнено, він відкриється так само, як після ручного End.

Timeline scrubbing

Під час перетягування timeline додаток оновлює поточний кадр з невеликою затримкою. Це зроблено навмисно, щоб VLC не отримував занадто багато seek-команд під час швидкого drag.

Annotation JSON, резервна копія і явна перевірка

Після відкриття відео додаток одразу й атомарно створює results/<video>.annotations.json, навіть якщо intervals порожній. Це єдиний актуальний файл для передачі. Після кожної зміни попередня валідна версія зберігається поруч як .bak, а основний JSON оновлюється.

У правій частині нижнього status bar видно Saving…, ✓ Saved з часом або Save failed. File → Validate & Save Annotations перевіряє документ і повторює запис; File → Show Annotation File in Folder доступний лише після створення JSON.

Надсилання через API

Connection → Settings… зберігає upload endpoint URL і token локально на цьому комп'ютері. Token не додається до annotation JSON. File → Upload Annotations… стає доступним після створення JSON, перевіряє та зберігає його, а потім надсилає весь вміст POST-запитом. Під час запиту показується модальне вікно прогресу. Після завершення додаток окремо повідомляє про успіх, помилку з'єднання/сервера або відхилений дублікат.

Якщо для відео вже є розмітка

Якщо для вибраного відео вже є файли розмітки, додаток запропонує:

- Continue Existing Work - продовжити попередню роботу.
- Start Over - почати заново.
- Delete Project - видалити файли розмітки для цього відео.
- Cancel - скасувати відкриття.

Важливі правила

- Start має бути раніше за End.
- Поки Start активний, жовтий індикатор показує його timestamp. Повторне натискання Start або A нічого не змінює; завершіть інтервал через End/D або скасуйте через Q.
- Якщо натиснути End без Start, інтервал не створиться.
- Якщо після Start відео було перемотано назад, перевірте, що End все ще пізніше за Start.
- У comment пишіть деталі, корисні для ревʼю. Категорію події краще тримати в event_type.
- Поворот 0°/90°/180°/270° вибирається через View → Video rotation і доступний тільки коли відео на паузі. Він змінює лише перегляд у додатку. Відеофайл і timestamp-и не змінюються.
"""


class AnnotatorHelpDialog(QDialog):
    def __init__(self, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self.setWindowTitle("Annotator Guide")
        self.resize(640, 620)

        text = QTextBrowser(self)
        text.setPlainText(HELP_TEXT)
        text.setOpenExternalLinks(False)

        buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
        buttons.rejected.connect(self.reject)

        layout = QVBoxLayout(self)
        layout.addWidget(text)
        layout.addWidget(buttons)
